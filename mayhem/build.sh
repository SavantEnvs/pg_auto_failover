#!/usr/bin/env bash
#
# mayhem/build.sh — build pg_auto_failover's fuzz harnesses, standalone reproducers, the KAT probe and
# upstream's monitor extension (for its regression suite).
#
# The fuzzed code is src/bin/common (parsing, ini, pgsql helpers) plus the vendored log/parson/
# snprintf/commandline libs. They are compiled from source twice: sanitized (ASan+UBSan, libFuzzer
# coverage) for the harnesses, and with normal flags for the KAT probe that mayhem/test.sh runs.
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

: "${SRC:=/mayhem}"
cd "$SRC"

BIN="$SRC/src/bin"
LIB="$BIN/lib"
OUT="$SRC/mayhem/build"
TARGETS="fuzz_versions fuzz_dotted_version fuzz_pguri fuzz_controldata fuzz_notification fuzz_timeline"

# git-version.h is generated by upstream's Makefile and is gitignored: recreate it every run.
printf '#define GIT_VERSION "mayhem"\n' > "$BIN/pg_autoctl/git-version.h"

PG_INCLUDES="-I$(pg_config --includedir) -I$(pg_config --includedir-server) -I$(pg_config --pkgincludedir)/internal"
PROJECT_INCLUDES="-I$BIN/common -I$BIN/pg_autoctl -I$LIB/pg -I$LIB/log/src -I$LIB/subcommands.c -I$LIB/libs -I$LIB/parson -I$BIN/common/vendor/pg_receivewal"
BASE_FLAGS="-D_GNU_SOURCE -D_WANT_SEMUN -Wno-everything $PG_INCLUDES $PROJECT_INCLUDES"

# The sources every harness links: all of src/bin/common, the vendored libs, pg_autoctl/state.c (node
# state names) and the globals main.c would normally define.
LIB_SOURCES="$(ls "$BIN"/common/*.c) $LIB/log/src/log.c $LIB/pg/snprintf.c $LIB/pg/strerror.c $LIB/parson/parson.c $LIB/subcommands.c/commandline.c $BIN/pg_autoctl/state.c $SRC/mayhem/globals.c"

LIBS="-L$(pg_config --pkglibdir) -L$(pg_config --libdir) $(pg_config --libs) -lpq -lm"

# compile_lib <dir> <flags...>: compile every library source into <dir>/obj and archive it.
compile_lib() {
  local dir="$1"; shift
  rm -rf "$dir"; mkdir -p "$dir/obj"
  local src pid pids=() failed=0
  for src in $LIB_SOURCES; do
    $CC $BASE_FLAGS "$@" -c "$src" -o "$dir/obj/$(basename "$(dirname "$src")")_$(basename "$src" .c).o" &
    pids+=($!)
    if [ "${#pids[@]}" -ge "$MAYHEM_JOBS" ]; then
      wait "${pids[0]}" || failed=1
      pids=("${pids[@]:1}")
    fi
  done
  for pid in "${pids[@]}"; do wait "$pid" || failed=1; done
  [ "$failed" -eq 0 ] || return 1
  rm -f "$dir/libpgaf.a"
  ar rcs "$dir/libpgaf.a" "$dir"/obj/*.o
}

# 1) project, sanitized + libFuzzer coverage + DWARF 3
# shellcheck disable=SC2086
compile_lib "$OUT/san" $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link -O1

# 2) harnesses: fuzzer binary and standalone reproducer, both with the lsan_off hook
# shellcheck disable=SC2086
$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRC/mayhem/lsan_off.cc" -o "$OUT/lsan_off.o"
# shellcheck disable=SC2086
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OUT/standalone_main.o"

for t in $TARGETS; do
  # shellcheck disable=SC2086
  $CC $BASE_FLAGS $SANITIZER_FLAGS $DEBUG_FLAGS -O1 -fsanitize=fuzzer-no-link -I"$SRC/mayhem" \
      -c "$SRC/mayhem/$t.c" -o "$OUT/$t.o"
  # shellcheck disable=SC2086
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$OUT/$t.o" "$OUT/lsan_off.o" \
      "$OUT/san/libpgaf.a" $LIBS -o "$SRC/$t"
  # shellcheck disable=SC2086
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$OUT/$t.o" "$OUT/standalone_main.o" "$OUT/lsan_off.o" \
      "$OUT/san/libpgaf.a" $LIBS -o "$SRC/$t-standalone"
done

# 3) oracle: the KAT probe with the project's normal flags, independent of the sanitized build
# shellcheck disable=SC2086
compile_lib "$OUT/norm" -O2 $COVERAGE_FLAGS
# shellcheck disable=SC2086
$CC $BASE_FLAGS -O2 $COVERAGE_FLAGS -I"$SRC/mayhem" "$SRC/mayhem/kat.c" "$OUT/norm/libpgaf.a" \
    $LIBS $COVERAGE_FLAGS -o "$OUT/kat"

# 4) upstream's monitor extension (PGXS, upstream's own Makefile and flags, no sanitizers), installed
#    into the PostgreSQL 17 server so mayhem/test.sh can run its pg_regress + isolation suite.
#    CC is left to PGXS (pg_config's compiler) because the Makefile's -Werror assumes it.
env -u CC -u CFLAGS make -C "$SRC/src/monitor" -j"$MAYHEM_JOBS" install
